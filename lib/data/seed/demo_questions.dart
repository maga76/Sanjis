/// Демо-темы и вопросы по всем 15 предметам: по 2 темы и 10 вопросов в теме
/// (вторые 5 вопросов каждой темы — в `demo_questions_extra.dart`).
/// Пока Firebase не подключён, тесты работают на этих данных;
/// на этапе 3 этим же списком заполнится Firestore.
///
/// Таджикские тексты должен проверить носитель языка.

/// Вопрос в краткой записи. Правильный вариант всегда первый —
/// при показе варианты перемешиваются.
class _Q {
  const _Q(
    this.tg,
    this.ru,
    this.optionsTg, {
    this.optionsRu,
    this.explainTg,
    this.explainRu,
  });

  final String tg;
  final String ru;
  final List<String> optionsTg;

  /// Если не задано — варианты одинаковые на обоих языках (числа, формулы).
  final List<String>? optionsRu;
  final String? explainTg;
  final String? explainRu;

  Question build(String id, String topicId) {
    assert(optionsRu == null || optionsRu!.length == optionsTg.length);
    return Question(
      id: id,
      topicId: topicId,
      textTg: tg,
      textRu: ru,
      optionsTg: optionsTg,
      optionsRu: optionsRu ?? optionsTg,
      correctIndex: 0,
      explanationTg: explainTg,
      explanationRu: explainRu ?? explainTg,
    );
  }
}

Topic _topic(
  String subjectId,
  String id,
  String nameTg,
  String nameRu,
  int minGrade,
  int maxGrade,
  List<_Q> questions,
) {
  final topicId = '$subjectId.$id';
  return Topic(
    id: topicId,
    subjectId: subjectId,
    nameTg: nameTg,
    nameRu: nameRu,
    minGrade: minGrade,
    maxGrade: maxGrade,
    questions: [
      for (final (i, q) in [...questions, ...?_extraQuestions[topicId]].indexed)
        q.build('$topicId.${i + 1}', topicId),
    ],
  );
}

